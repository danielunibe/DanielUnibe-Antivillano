export type LocaleDictionaryKey = keyof typeof dictionary.es;

const readLocale = (): Locale => window.localStorage.getItem(LOCALE_STORAGE_KEY) === 'en' ? 'en' : 'es';

export const LocaleProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
    const [locale, setLocale] = useState<Locale>(readLocale);

    useEffect(() => {
        window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
        document.documentElement.lang = locale;
    }, [locale]);

    const value = useMemo<LocaleContextValue>(() => ({
        locale,
        setLocale,
        t: key => dictionary[locale][key],
        text: value => value[locale],
    }), [locale]);

    return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};
